'use strict';
const fs=require('fs'),vm=require('vm'),path=require('path');
const src=fs.readFileSync(path.join(__dirname,'../Office/cctv.js'),'utf8');
const data=new Map();
const storage={getItem:k=>data.has(k)?data.get(k):null,setItem:(k,v)=>data.set(k,String(v))};
const ctx={window:{},localStorage:storage};vm.createContext(ctx);
vm.runInContext(src.slice(0,src.indexOf('/* ECHARPE Office CCTV')),ctx);
const read=ctx.window.ofCctvReadBasketOffset,save=ctx.window.ofCctvSaveBasketOffset;
const key=b=>'echarpe.cctv.'+b+'.basketOffsetMs';
assertEq(read('madinaty'),0,'No calibration defaults to zero');
data.set(key('madinaty'),'1200');
assertEq(read('madinaty'),1200,'Legacy calibration retained');
save('madinaty',1300);assertEq(read('madinaty'),1300,'Fine adjustment survives reopening');
save('madinaty',0);assertEq(read('madinaty'),0,'Explicit reset overrides legacy calibration');
data.set(key('madinaty')+'.v746','bad');assertEq(read('madinaty'),1200,'Invalid value falls back to valid legacy');
data.set(key('madinaty')+'.v746','16000');assertEq(read('madinaty'),1200,'Out of range value cannot poison calibration');
assertEq(save('madinaty',16000),15000,'Positive calibration limit preserved');
assertEq(save('rehab',-16000),-15000,'Negative calibration limit preserved');
assertEq(read('madinaty'),15000,'Branches remain isolated');
assertEq(read('rehab'),-15000,'Rehab uses its own calibration');
save('glow',100);assertEq(read('glow'),100,'100 ms adjustment retained');
ctx.localStorage={getItem(){throw Error('blocked')},setItem(){throw Error('blocked')}};
assertEq(read('glow'),0,'Blocked storage does not break viewer');
assertEq(save('glow',100),100,'Blocked storage still permits session adjustment');
// Exercise the shipped invoice initialization with POS timeline + NVR clock.
ctx.localStorage=storage;save('madinaty',1200);
Object.assign(ctx,{profile:{id:'madinaty'},d:{clockSource:'nvr_isapi'},timeline:{clockSource:'pos_pc'},sync:true});
vm.runInContext(src.match(/var basketBranch=String\(profile[\s\S]*?basketOffsetMs=window.ofCctvReadBasketOffset\(basketBranch\);/)[0],ctx);
assertEq(ctx.basketOffsetMs,1200,'POS clock label cannot discard saved camera calibration');
ctx.profile={id:'rehab'};vm.runInContext(src.match(/var basketBranch=String\(profile[\s\S]*?basketOffsetMs=window.ofCctvReadBasketOffset\(basketBranch\);/)[0],ctx);
assertEq(ctx.basketOffsetMs,-15000,'Invoice initialization resolves actual branch');
assert(!src.includes('autoClockSync')&&!src.includes('basketAutoClock'),'No unverified AUTO calibration');
assert(!src.includes('(basketOffsetMs/1000).toFixed(0)'),'Subsecond display is not rounded away');
// Execute actual timeline lookup at a subsecond boundary.
vm.runInContext(src.slice(src.indexOf('window.ofCctvTimelineStateAt='),src.indexOf('window.ofCctvInvoiceShot = async',src.indexOf('window.ofCctvTimelineStateAt='))),ctx);
const events=[{atMs:1100,kind:'item_added'},{atMs:1200,kind:'qty_increased'}];
assertEq(ctx.window.ofCctvTimelineStateAt(events,1000,0).event,null,'No event before its timestamp');
assertEq(ctx.window.ofCctvTimelineStateAt(events,1000,.1).event.kind,'item_added','100 ms offset reaches first event');
assertEq(ctx.window.ofCctvTimelineStateAt(events,1000,.2).event.kind,'qty_increased','200 ms offset reaches second event');
