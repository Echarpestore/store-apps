const fs=require('fs'), path=require('path'), assert=require('assert');
const root=path.join(__dirname,'..');
const live=fs.readFileSync(path.join(root,'pos','pos-live.js'),'utf8');
const sale=fs.readFileSync(path.join(root,'pos','pos-sale.js'),'utf8');
const pi=fs.readFileSync(path.join(root,'pos','index.html'),'utf8');
const oi=fs.readFileSync(path.join(root,'Office','index.html'),'utf8');
const oj=fs.readFileSync(path.join(root,'Office','office.js'),'utf8');
const rules=fs.readFileSync(path.join(root,'security','firestore-phase2.rules'),'utf8');
assert(live.includes("collection('office_pos_live')"),'POS publishes live collection');
assert(!/customerPhone|customerName/.test(live),'live payload must not expose customer identity');
assert(!/command|remoteControl|eval\(/i.test(live),'no remote control channel');
assert(sale.includes("typeof posLivePublish === 'function'"),'cart render publishes state');
assert(/pos-live\.js\?v=\d+/.test(pi),'POS loads live module');
assert(oi.includes('data-office-go="live"') && oi.includes('id="page-live"'),'Office has POS Live page');
assert(oj.includes("db.collection('office_pos_live').onSnapshot"),'Office uses realtime listener');
assert(oj.includes("if(page === 'live') ofLiveStart(); else ofLiveStop();"),'listener lives only while page is open');
const rb=rules.slice(rules.indexOf('match /office_pos_live/'), rules.indexOf('// ---------- المبيعات ----------'));
assert(rb.includes('allow read, create, update: if isStaff()'),'live data is staff-only');
assert(rb.includes('allow delete: if false'),'live docs cannot be deleted by client');
