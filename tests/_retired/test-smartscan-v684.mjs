check('auto capture and manual backup',()=>assert(tab.includes('captureReady(metrics,consecutive')&&tab.includes('finManualSnap')));
check('full image, no .9 crop',()=>assert(tab.includes('ctx.drawImage(video,0,0,srcW,srcH,0,0,canvas.width,canvas.height)')));
check('only one receipt upload from camera',()=>assert.equal((tab.match(/call\('instaSubmitPhoto'/g)||[]).length,1));
check('camera stops before upload',()=>assert(tab.indexOf('stream.getTracks().forEach(t=>t.stop());stream=null;',tab.indexOf('const upload=async')) <tab.indexOf("call('instaSubmitPhoto'",tab.indexOf('const upload=async'))));
check('no automatic print from local image analysis',()=>assert(!tab.includes('printReceipt(')&&!tab.includes('instaFinalizeSale')));
check('only InstaPay POS approval polling shortened',()=>assert(pos.includes("wait(name==='instaStatus'?850:1300)")));
check('strict OCR and recipient plus date checks kept',()=>assert(server.includes('confidence>=.92&&r.normalized.length>=75')&&server.includes('nearSession(r.date,s.createdAt)')&&server.includes('beneficiarySection.includes(alias)')));
