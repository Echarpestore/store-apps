import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname,resolve} from 'node:path';
import {inspectFrame,captureReady} from '../feedback/receipt-scan-core.js';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
let passed=0;const check=(name,fn)=>{fn();passed++;console.log('OK',name);};
const image=(pattern)=>{const width=240,height=180,data=new Uint8ClampedArray(width*height*4);for(let y=0;y<height;y++)for(let x=0;x<width;x++){const v=pattern(x,y),i=(y*width+x)*4;data[i]=data[i+1]=data[i+2]=v;data[i+3]=255;}return {width,height,data};};
const blank=image(()=>255);
const receipt=image((x,y)=>x>18&&x<221&&y>10&&y<170 ? ((y%13<2&&x%9<7)||(x%17<2&&y%13<9)?25:236) : 55);
let prev=inspectFrame(receipt).sample;
const first=inspectFrame(receipt),stable=inspectFrame(receipt,prev);
check('blank screen not auto-captured',()=>assert.equal(inspectFrame(blank,inspectFrame(blank).sample).ready,false));
check('first frame never auto-captured',()=>assert.equal(first.ready,false));
check('stable printed receipt detected',()=>assert.equal(stable.ready,true));
check('two frames do not trigger capture',()=>assert.equal(captureReady(stable,2,1200),false));
check('three frames cannot trigger before 650ms',()=>assert.equal(captureReady(stable,3,400),false));
check('stable third frame triggers capture',()=>assert.equal(captureReady(stable,3,800),true));
const moved=image((x,y)=>receipt.data[(y*240+((x+30)%240))*4]);
check('moving image rejected as stable',()=>assert.equal(inspectFrame(moved,prev).stable,false));
const tab=readFileSync(resolve(root,'feedback/finance-tablet.js'),'utf8');
const pos=readFileSync(resolve(root,'pos/finance-pos.js'),'utf8');
